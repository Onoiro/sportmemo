"""Контекстные процессоры SportMemo."""

from django.conf import settings


def project_info(request):
    """Версия и имя проекта — доступны во всех шаблонах."""
    return {
        "SPORTMEMO_VERSION": settings.VERSION,
        "SPORTMEMO_SITE_NAME": "SportMemo",
    }


def seo_meta(request):
    """Безопасный дефолт метатегов: всё неописанное закрыто от индексации.

    Публичные представления передают в контекст свой полный словарь `meta`
    (из `apps.core.seo.page_meta`), и он перекрывает значение процессора:
    контекст представления в `Context.dicts` лежит выше вывода процессоров,
    а обход идёт от последнего к первому. Проверено на практике, не догадка.

    Дефолт намеренно осторожный: новая страница без метатегов не попадёт
    в поисковики, пока автор не опишет её явно. Обратная ошибка — служебная
    страница в выдаче — заметнее и неприятнее.
    """
    return {"meta": {"noindex": True}}
